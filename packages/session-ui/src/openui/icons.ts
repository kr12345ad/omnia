export function legacyIconName(name: unknown): LegacyName | undefined {
  if (typeof name !== "string") return undefined
  return LEGACY[name.trim().toLowerCase()]
}

export function v2IconName(name: unknown): V2Name | undefined {
  if (typeof name !== "string") return undefined
  return V2[name.trim().toLowerCase()]
}
