import { join, normalize, extname } from "node:path"
import { existsSync, statSync } from "node:fs"

const root = import.meta.dir
const port = Number(process.env.PORT ?? 4173)
const downloads = process.env.OMNIA_DOWNLOADS_DIR ?? join(process.env.HOME ?? root, "omnia-downloads")

const headers = {
  "cache-control": "public, max-age=300",
  "content-security-policy":
    "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'; object-src 'none'; frame-ancestors 'none'; base-uri 'self'",
  "permissions-policy": "geolocation=(), camera=(), microphone=()",
  "referrer-policy": "no-referrer",
  "strict-transport-security": "max-age=31536000; includeSubDomains",
  "x-content-type-options": "nosniff",
  "x-frame-options": "DENY",
}

const types: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
  ".AppImage": "application/octet-stream",
  ".deb": "application/vnd.debian.binary-package",
  ".rpm": "application/x-rpm",
  ".exe": "application/vnd.microsoft.portable-executable",
  ".dmg": "application/x-apple-diskimage",
  ".zip": "application/zip",
}

function inside(base: string, target: string) {
  const path = normalize(target)
  return path === base || path.startsWith(base + "/")
}

function file(path: string) {
  if (!existsSync(path) || !statSync(path).isFile()) return
  return new Response(Bun.file(path), {
    headers: {
      ...headers,
      "content-type": types[extname(path)] ?? "application/octet-stream",
      ...(extname(path) in types && !types[extname(path)]!.startsWith("text/") ? {} : {}),
    },
  })
}

const server = Bun.serve({
  hostname: "127.0.0.1",
  port,
  fetch(request) {
    const url = new URL(request.url)
    const proto = request.headers.get("x-forwarded-proto")?.split(",")[0]?.trim()
    if (proto === "http") {
      return Response.redirect(`https://${url.host}${url.pathname}${url.search}`, 301)
    }

    const path = decodeURIComponent(url.pathname)

    // Downloads are hosted from a directory outside the repo so the artifacts
    // do not enter git. /downloads/SHA256SUMS is generated by the release step.
    if (path.startsWith("/downloads/")) {
      const target = join(downloads, path.slice("/downloads/".length))
      if (inside(downloads, target)) return file(target) ?? new Response("Not found", { status: 404, headers })
      return new Response("Not found", { status: 404, headers })
    }

    // Every other path is a static site file. "/" serves index.html.
    const relative = path === "/" ? "index.html" : path.slice(1)
    const target = join(root, relative)
    if (inside(root, target) && !target.startsWith(join(root, "vendor") + "/downloads")) {
      return file(target) ?? new Response("Not found", { status: 404, headers })
    }
    return new Response("Not found", { status: 404, headers })
  },
})

console.log(`Omnia site -> ${server.url} (downloads from ${downloads})`)
