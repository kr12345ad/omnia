// Regenerate the embedded gRPC descriptor after changing a .proto file.
//
// The server ships the serialized FileDescriptorSet instead of reading .proto
// files at runtime. That keeps `bun build --compile` working without a runtime
// asset path, while the vendored files remain the reviewable source of truth.
// Run with: bun run generate:grpc
import { writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join, resolve } from "node:path"
import protobuf from "protobufjs"
import { FileDescriptorSet } from "protobufjs/ext/descriptor"
import "protobufjs/ext/descriptor"

const require = createRequire(import.meta.url)
const protoRoot = resolve(import.meta.dir, "../src/server/grpc/proto")
const protobufRoot = dirname(require.resolve("protobufjs/package.json"))
const root = new protobuf.Root()

root.resolvePath = (_origin, target) => {
  if (target.startsWith("/")) return target
  if (target.startsWith("github.com/openconfig/gnmi/proto/")) {
    return join(protoRoot, target.slice("github.com/openconfig/gnmi/proto/".length))
  }
  if (target.startsWith("google/protobuf/")) return join(protobufRoot, target)
  return join(protoRoot, target)
}

await root.load([join(protoRoot, "gnmi.proto"), join(protoRoot, "omnia.proto")], { keepCase: true })
root.resolveAll()
const descriptor = root.toDescriptor("proto3")
const bytes = Buffer.from(FileDescriptorSet.encode(descriptor).finish())
const output = resolve(import.meta.dir, "../src/server/grpc/generated/descriptor.ts")

writeFileSync(
  output,
  `// Generated by script/generate-grpc-descriptor.ts. Do not edit by hand.\n` +
    `// Sources: src/server/grpc/proto/gnmi.proto, gnmi_ext/gnmi_ext.proto, omnia.proto\n` +
    `export const GNMI_DESCRIPTOR_BASE64 =\n  "${bytes.toString("base64")}"\n`,
)
console.log(`wrote ${output} (${bytes.length} bytes)`)
